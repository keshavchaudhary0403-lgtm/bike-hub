// Writes supabase/migrations/014_bike_models_seed.sql from src/data/bike-models.ts.
// Usage: npm run bike-models:sql   (re-run after editing the bike list, then apply the migration)
import {writeFileSync} from "node:fs";
import {BIKE_MODELS} from "../src/data/bike-models.ts";

const q=v=>v==null?"null":typeof v==="number"||typeof v==="boolean"?String(v):`'${String(v).replace(/'/g,"''")}'`;
const arr=a=>`array[${a.map(q).join(",")}]::text[]`;
const rows=BIKE_MODELS.map(m=>`  (${[q(m.id),q(m.brand),q(m.model),q(m.variant),q(m.level),q(m.cc),q(m.fuel),arr(m.brandTools),q(m.current),q(m.years),q(m.needsReview)].join(",")})`);
const sql=`-- Generated by scripts/bike-models-sql.mjs from src/data/bike-models.ts. Edit that file, not this one.
insert into public.bike_models (id,brand,model,variant,bike_level,cc,fuel,brand_tools_required,is_current_in_india,years,needs_review) values
${rows.join(",\n")}
on conflict (id) do update set brand=excluded.brand,model=excluded.model,variant=excluded.variant,bike_level=excluded.bike_level,cc=excluded.cc,fuel=excluded.fuel,
  brand_tools_required=excluded.brand_tools_required,is_current_in_india=excluded.is_current_in_india,years=excluded.years,needs_review=excluded.needs_review;
`;
writeFileSync("supabase/migrations/014_bike_models_seed.sql",sql);
console.log(`${BIKE_MODELS.length} bike models written (${BIKE_MODELS.filter(m=>m.needsReview).length} need review).`);
const ids=BIKE_MODELS.map(m=>m.id);const dup=ids.filter((x,i)=>ids.indexOf(x)!==i);if(dup.length){console.error("Duplicate ids:",dup);process.exit(1)}
